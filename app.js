function applyFilters() {
  FilterState.ci = document.getElementById('filterCI')?.value || "ALL";
  FilterState.group = document.getElementById('filterGroup')?.value || "ALL";
  FilterState.search = (document.getElementById('globalSearch')?.value || "").toLowerCase().trim();

  filteredData = INCIDENTS.filter(item => {
    if (!FilterState.priorities.includes(item.priority)) return false;
    if (FilterState.ci !== "ALL" && item.cmdb_ci !== FilterState.ci) return false;
    if (FilterState.group !== "ALL" && item.assignment_group !== FilterState.group) return false;
    if (FilterState.problemOnly && !item.problem_candidate) return false;
    if (FilterState.changeOnly && !item.related_change) return false;
    if (FilterState.search !== "") {
      const match = item.number.toLowerCase().includes(FilterState.search) ||
                    item.source_incident_id.toLowerCase().includes(FilterState.search) ||
                    item.cmdb_ci.toLowerCase().includes(FilterState.search) ||
                    item.technical_cause.toLowerCase().includes(FilterState.search) ||
                    item.assigned_to.toLowerCase().includes(FilterState.search) ||
                    (item.related_change && item.related_change.toLowerCase().includes(FilterState.search));
      if (!match) return false;
    }
    return true;
  });

  let activeCount = 0;
  if (FilterState.priorities.length < 4) activeCount++;
  if (FilterState.ci !== "ALL") activeCount++;
  if (FilterState.group !== "ALL") activeCount++;
  if (FilterState.problemOnly) activeCount++;
  if (FilterState.changeOnly) activeCount++;
  if (FilterState.search !== "") activeCount++;

  const badge = document.getElementById('activeFilterBadge');
  if (badge) {
    badge.textContent = activeCount;
    badge.classList.toggle('hidden', activeCount === 0);
  }

  const prbCount = filteredData.filter(d => d.problem_candidate).length;
  const chgCount = filteredData.filter(d => d.related_change).length;
  const prbBadge = document.getElementById('cntProblemBadge');
  const chgBadge = document.getElementById('cntChangeBadge');
  if (prbBadge) prbBadge.textContent = prbCount;
  if (chgBadge) chgBadge.textContent = chgCount;

  TableState.breach.page = 1;
  TableState.problem.page = 1;
  TableState.change.page = 1;

  updateURLState();
  updateExecutiveKPIs();
  renderActiveTabVisuals();
}

function updateExecutiveKPIs() {
  const total = filteredData.length;
  const kpiTotalEl = document.getElementById('kpiTotal');
  if (kpiTotalEl) kpiTotalEl.textContent = total;

  if (total === 0) {
    if (document.getElementById('kpiSLAComp')) document.getElementById('kpiSLAComp').textContent = "0.0%";
    if (document.getElementById('kpiSLABreach')) document.getElementById('kpiSLABreach').textContent = "0";
    if (document.getElementById('kpiMTTR')) document.getElementById('kpiMTTR').textContent = "0.0h";
    if (document.getElementById('kpiMajor')) document.getElementById('kpiMajor').textContent = "0";
    if (document.getElementById('kpiProb')) document.getElementById('kpiProb').textContent = "0";
    return;
  }

  const breaches = filteredData.filter(d => d.has_breached).length;
  const compRate = (((total - breaches) / total) * 100).toFixed(1);
  const totalHours = filteredData.reduce((acc, cur) => acc + cur.resolution_duration_hours, 0);
  const mttr = (totalHours / total).toFixed(1);
  const major = filteredData.filter(d => d.priority <= 2).length;
  const prob = filteredData.filter(d => d.problem_candidate).length;

  if (document.getElementById('kpiSLAComp')) {
    const el = document.getElementById('kpiSLAComp');
    el.textContent = `${compRate}%`;
    el.className = parseFloat(compRate) >= 90.0
      ? 'text-2xl sm:text-3xl font-extrabold text-slaMet mt-1'
      : 'text-2xl sm:text-3xl font-extrabold text-p1 mt-1';
  }
  if (document.getElementById('kpiSLABreach')) document.getElementById('kpiSLABreach').textContent = breaches;
  if (document.getElementById('kpiMTTR')) document.getElementById('kpiMTTR').textContent = `${mttr}h`;
  if (document.getElementById('kpiMajor')) document.getElementById('kpiMajor').textContent = major;
  if (document.getElementById('kpiProb')) document.getElementById('kpiProb').textContent = prob;

  CIs.forEach(ciName => {
    const list = filteredData.filter(d => d.cmdb_ci === ciName);
    const cVol = list.length;
    const cBr = cVol > 0 ? (((list.filter(d => d.has_breached).length) / cVol) * 100).toFixed(0) : 0;
    let nodeSuffix = '';
    if (ciName.includes('SSO')) nodeSuffix = 'sso';
    else if (ciName.includes('Load')) nodeSuffix = 'lb';
    else if (ciName.includes('Web')) nodeSuffix = 'web';
    else if (ciName.includes('Cluster')) nodeSuffix = 'cluster';
    else if (ciName.includes('Database')) nodeSuffix = 'db';

    const textNode = document.querySelector(`#svg_node_${nodeSuffix} ~ text:last-of-type`);
    if (textNode) {
      textNode.textContent = `${cVol} Incidents • ${cBr}% Breach`;
    }
  });
}

